#!/usr/bin/env bash
# Sync code to the home PC, then run a command there in a detached tmux
# session with the `ml` conda env active, logging to logs/<run-name>.log
# in the remote project dir.
#
# Usage: scripts/remote/train.sh "<command>" [run-name]
#
# Example:
#   scripts/remote/train.sh \
#     "python -m bouquet_checker train-plantnet --config configs/plantnet_baseline.json" \
#     plantnet-baseline
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=./_common.sh
source "$SCRIPT_DIR/_common.sh"

if [ "$#" -lt 1 ]; then
  echo "usage: train.sh \"<command>\" [run-name]" >&2
  exit 1
fi

CMD="$1"
RUN_NAME="${2:-$(date +%Y%m%d-%H%M%S)}"
validate_run_name "$RUN_NAME"

check_ssh
check_tmux

if ssh "$SSH_HOST" "tmux has-session -t '$RUN_NAME'" 2>/dev/null; then
  echo "error: a tmux session named '$RUN_NAME' is already running." >&2
  echo "       pick a different run name, or stop it first:" >&2
  echo "       scripts/remote/stop.sh $RUN_NAME" >&2
  exit 1
fi

echo "== syncing code =="
"$SCRIPT_DIR/sync.sh"

RUN_DIR="$REMOTE_DIR/.remote_runs"
RUN_SCRIPT="$RUN_DIR/$RUN_NAME.sh"
LOG_FILE="$REMOTE_DIR/logs/$RUN_NAME.log"

echo "== writing run script on $SSH_HOST =="
# The command is written into its own script file, on its own line, and
# only ever executed there - never re-quoted through ssh/tmux as a single
# giant string - so whatever quoting the command itself needs (flags with
# spaces, etc.) is parsed exactly once, normally, by the shell that runs it.
ssh "$SSH_HOST" "mkdir -p '$RUN_DIR' '$REMOTE_DIR/logs' && cat > '$RUN_SCRIPT'" <<EOF
#!/usr/bin/env bash
# Generated by train.sh for run '$RUN_NAME' - not meant to be hand-edited.
set -e
cd "$REMOTE_DIR"
$REMOTE_CONDA_ACTIVATE
$CMD
EOF

echo "== launching '$RUN_NAME' in tmux on $SSH_HOST =="
ssh "$SSH_HOST" \
  "chmod +x '$RUN_SCRIPT' && tmux new-session -d -s '$RUN_NAME' \"bash '$RUN_SCRIPT' > '$LOG_FILE' 2>&1\""

echo
echo "run name:   $RUN_NAME"
echo "check on it: scripts/remote/status.sh $RUN_NAME"
echo "attach live: ssh $SSH_HOST -t \"tmux attach -t $RUN_NAME\""
echo "log file:    $SSH_HOST:$LOG_FILE"
echo "stop it:     scripts/remote/stop.sh $RUN_NAME"
